from typing import Protocol


class LabelStore(Protocol):
    def labels(self, item_id: str) -> list[str]: ...
    def replace_labels(self, item_id: str, labels: list[str]) -> None:
        """Persist the item's complete ordered label collection."""
        ...

    def delete_labels(self, item_id: str) -> None: ...
    def insert_label(self, item_id: str, position: int, label: str) -> None: ...
    def flush(self) -> None: ...
